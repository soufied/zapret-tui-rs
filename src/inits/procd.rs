//! procd service manager for OpenWrt.
//!
//! Writes an `/etc/init.d` script that uses `/etc/rc.common` and `USE_PROCD`.
//! procd supervises the process and sends SIGTERM on stop, which the binary
//! handles by removing its firewall rules before exiting.

use crate::inits::ServiceManager;
use std::fs;
use std::path::Path;
use std::process::Command;

const START_PRIORITY: u32 = 99;

pub struct ProcdManager {
    name: &'static str,
}

impl ProcdManager {
    pub fn new(name: &'static str) -> Self {
        Self { name }
    }

    fn script_path(&self) -> String {
        format!("/etc/init.d/{}", self.name)
    }

    fn rc_link_path(&self) -> String {
        format!("/etc/rc.d/S{}{}", START_PRIORITY, self.name)
    }

    /// Reads the `PROG="..."` assignment back out of the generated script.
    fn program_path(&self) -> Option<String> {
        let content = fs::read_to_string(self.script_path()).ok()?;
        content
            .lines()
            .find_map(|line| line.strip_prefix("PROG=\""))
            .map(|rest| rest.trim_end_matches('"').to_string())
    }

    fn run_action(&self, action: &str) -> Result<(), String> {
        let script = self.script_path();
        let output = Command::new(&script)
            .arg(action)
            .output()
            .map_err(|e| format!("{}{}", rust_i18n::t!("err_exec_init"), e))?;

        if output.status.success() {
            Ok(())
        } else {
            let stderr = String::from_utf8_lossy(&output.stderr).trim().to_string();
            Err(format!(
                "{} {} failed: {}",
                script,
                action,
                if stderr.is_empty() {
                    format!("exit code {:?}", output.status.code())
                } else {
                    stderr
                }
            ))
        }
    }
}

fn script_content(name: &str, desc: &str, exe: &str, config: &str, cache: &str) -> String {
    format!(
        r#"#!/bin/sh /etc/rc.common
# {desc}
# Generated by zapret-rust. Changes made here are overwritten on reinstall.

START={start}
STOP=10
USE_PROCD=1

NAME="{name}"
PROG="{exe}"
CONFIG="{config}"
CACHE_DIR="{cache}"

start_service() {{
    procd_open_instance
    procd_set_param command "$PROG" --config "$CONFIG" --cache-dir "$CACHE_DIR"
    procd_set_param respawn 3600 5 5
    procd_set_param stdout 1
    procd_set_param stderr 1
    procd_set_param file "$CONFIG"
    procd_close_instance
}}
"#,
        start = START_PRIORITY,
        desc = desc,
        name = name,
        exe = exe,
        config = config,
        cache = cache,
    )
}

impl ServiceManager for ProcdManager {
    fn is_installed(&self) -> bool {
        Path::new(&self.script_path()).exists()
    }

    fn is_enabled(&self) -> bool {
        Path::new(&self.rc_link_path()).exists()
    }

    fn is_active(&self) -> bool {
        let Some(program) = self.program_path() else {
            return false;
        };
        Command::new("pgrep")
            .args(["-f", &program])
            .output()
            .map(|o| o.status.success())
            .unwrap_or(false)
    }

    fn install(&self, exe_path: &Path, config_path: &Path, cache_dir: &Path) -> Result<(), String> {
        let exe = exe_path
            .to_str()
            .ok_or(rust_i18n::t!("err_invalid_exe").into_owned())?;
        let config = config_path
            .to_str()
            .ok_or(rust_i18n::t!("err_invalid_cfg").into_owned())?;
        let cache = cache_dir
            .to_str()
            .ok_or(rust_i18n::t!("err_invalid_cache").into_owned())?;

        let content = script_content(
            self.name,
            crate::inits::service_description(self.name),
            exe,
            config,
            cache,
        );

        let script_path = self.script_path();
        fs::write(&script_path, content).map_err(|e| format!("{}{}", rust_i18n::t!("err_write_sysv"), e))?;

        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(&script_path, fs::Permissions::from_mode(0o755))
                .map_err(|e| format!("{}{}", rust_i18n::t!("err_chmod_sysv"), e))?;
        }

        self.run_action("enable")
    }

    fn uninstall(&self) -> Result<(), String> {
        let _ = self.run_action("stop");
        if self.is_installed() {
            let _ = self.run_action("disable");
            fs::remove_file(self.script_path()).map_err(|e| format!("{}{}", rust_i18n::t!("err_rm_sysv"), e))?;
        }
        Ok(())
    }

    fn start(&self) -> Result<(), String> {
        self.run_action("start")
    }

    fn stop(&self) -> Result<(), String> {
        self.run_action("stop")
    }

    fn restart(&self) -> Result<(), String> {
        self.run_action("restart")
    }
}
